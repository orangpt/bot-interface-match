"""
Запрос к ИИ: рекомендации по улучшению резюме и скрытые навыки на основе текста резюме.
"""
import os

from openai import OpenAI


SYSTEM_PROMPT = """Ты — эксперт по карьере и подбору персонала. Тебе дают текст резюме (или структурированные данные из резюме).
Твоя задача:
1) Кратко и по делу подсказать, что улучшить в резюме (2–5 конкретных пунктов).
2) Назвать скрытые навыки человека — то, что не указано явно, но можно вывести из опыта, образования и формулировок (3–7 пунктов). Формулируй как сильные стороны и потенциал.
3) Исходя из существующего опыта и стека, предложить какие еще технологии и навыки может знать человек. Должно быть вертикальное перечисление с нумерацией. 

Отвечай на языке текста резюме. Структурируй ответ тремя блоками с заголовками:
**Что улучшить**
...
**Скрытые навыки и сильные стороны**
...
**Технологии и навыки**
..."""


def get_analysis(resume_text: str, *, api_key: str | None = None) -> str:
    """
    Отправляет текст резюме в ИИ, возвращает текст с рекомендациями и скрытыми навыками.
    api_key: ключ OpenAI (или берётся из OPENAI_API_KEY).
    """
    key = api_key or os.getenv("OPENAI_API_KEY")
    if not key:
        return (
            "ИИ-анализ недоступен: не задан OPENAI_API_KEY. "
            "Добавьте ключ в .env и перезапустите бота."
        )

    client = OpenAI(api_key=key)
    response = client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": f"Резюме:\n\n{resume_text[:12000]}"},
        ],
        temperature=0.3,
        max_tokens=1500,
    )
    choice = response.choices[0]
    return (choice.message.content or "").strip()
